using System.Collections.Immutable;
using System.Globalization;
using System.Text;
using System.Xml;
using System.Xml.Linq;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;

namespace RitsukageGif.IconGenerator
{
    [Generator]
    public sealed class SvgIconGenerator : IIncrementalGenerator
    {
        private static readonly DiagnosticDescriptor InvalidIcon = new(
            "RGIG001", "Invalid or unsupported SVG icon", "Icon '{0}': {1}", "IconGeneration",
            DiagnosticSeverity.Error, true);

        private static readonly DiagnosticDescriptor DuplicateKey = new(
            "RGIG002", "Duplicate SVG icon key", "SVG icon key '{0}' is used by more than one file",
            "IconGeneration", DiagnosticSeverity.Error, true);

        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            var icons = context.AdditionalTextsProvider
                .Where(static file =>
                    string.Equals(Path.GetExtension(file.Path), ".svg", StringComparison.OrdinalIgnoreCase))
                .Select(static (file, token) => new SvgInput(file.Path, file.GetText(token)))
                .Collect();
            context.RegisterSourceOutput(icons, Generate);
        }

        private static void Generate(SourceProductionContext context, ImmutableArray<SvgInput> inputs)
        {
            var body = new StringBuilder();
            var fields = new StringBuilder();
            var keys = new HashSet<string>(StringComparer.Ordinal);
            foreach (var input in inputs.OrderBy(static input => input.Path, StringComparer.Ordinal))
            {
                var key = Path.GetFileNameWithoutExtension(input.Path);
                var location = Location.Create(input.Path, default, default);
                if (!keys.Add(key))
                {
                    context.ReportDiagnostic(Diagnostic.Create(DuplicateKey, location, key));
                    continue;
                }

                try
                {
                    var icon = ParseIcon(input);
                    var field = "Definition" + fields.Length.ToString(CultureInfo.InvariantCulture);
                    fields.Append("        private static readonly IconDefinition ").Append(field).Append(" = ")
                        .Append(icon.Definition).Append(";\n");
                    body.Append("                    case ").Append(Literal(key)).Append(":\n");
                    foreach (var alias in icon.Aliases)
                    {
                        if (!keys.Add(alias))
                        {
                            context.ReportDiagnostic(Diagnostic.Create(DuplicateKey, location, alias));
                            continue;
                        }

                        body.Append("                    case ").Append(Literal(alias)).Append(":\n");
                    }

                    body.Append("                        definition = ").Append(field)
                        .Append(";\n                        return true;\n");
                }
                catch (Exception exception) when
                    (exception is XmlException or InvalidDataException or ArgumentException)
                {
                    context.ReportDiagnostic(Diagnostic.Create(InvalidIcon, location, key, exception.Message));
                }
            }

            context.AddSource("IconCatalog.g.cs", SourceText.From("""
                                                                  // <auto-generated/>
                                                                  #nullable enable
                                                                  namespace RitsukageGif.Desktop.Icons
                                                                  {
                                                                      internal static partial class IconCatalog
                                                                      {
                                                                  """ + "\n" + fields + """
                        internal static bool TryGetDefinition(string key, out IconDefinition definition)
                        {
                            switch (key)
                            {
                """ + "\n" + body + """
                                                    default:
                                                        definition = default!;
                                                        return false;
                                                }
                                            }
                                        }
                                    }
                                    """, Encoding.UTF8));
        }

        private static ParsedIcon ParseIcon(SvgInput input)
        {
            if (input.Text is null) throw new InvalidDataException("The SVG file could not be read.");
            using var reader = XmlReader.Create(new StringReader(input.Text.ToString()), new()
            {
                DtdProcessing = DtdProcessing.Prohibit, XmlResolver = null,
            });
            var document = XDocument.Load(reader, LoadOptions.SetLineInfo);
            var root = document.Root ?? throw new InvalidDataException("The SVG root is missing.");
            if (root.Name.LocalName != "svg" || root.Name.NamespaceName is not ("" or "http://www.w3.org/2000/svg"))
                throw new InvalidDataException("The root must be an SVG element.");
            ValidateAttributes(root, true);
            var aliasText = (string?)root.Attribute("data-aliases");
            var aliases = aliasText is null ? [] : aliasText.Split(';').Select(static alias => alias.Trim()).ToArray();
            if (aliases.Any(string.IsNullOrWhiteSpace))
                throw new InvalidDataException("data-aliases must contain nonempty semicolon-separated keys.");
            var viewBox = ((string?)root.Attribute("viewBox") ?? "").Split([' ', '\t', '\r', '\n', ','],
                StringSplitOptions.RemoveEmptyEntries);
            if (viewBox.Length != 4) throw new InvalidDataException("An explicit four-number viewBox is required.");
            var numbers = viewBox.Select(ParseNumber).ToArray();
            if (numbers[2] <= 0 || numbers[3] <= 0)
                throw new InvalidDataException("viewBox dimensions must be positive.");
            foreach (var dimension in new[] { "width", "height" })
            {
                var value = (string?)root.Attribute(dimension);
                if (value is not null && value is not ("24" or "24px"))
                    throw new InvalidDataException(
                        $"{dimension} must be 24 or 24px; use viewBox for source coordinates.");
            }

            var paths = new List<string>();
            foreach (var node in root.Nodes())
            {
                if (node is XComment || (node is XText text && string.IsNullOrWhiteSpace(text.Value))) continue;
                if (node is not XElement path || path.Name.LocalName != "path" ||
                    path.Name.Namespace != root.Name.Namespace)
                    throw new InvalidDataException("Only path children are supported.");
                ValidateAttributes(path, false);
                if (path.Nodes().Any()) throw new InvalidDataException("Path elements must not contain child content.");
                var data = (string?)path.Attribute("d");
                SvgPathValidator.Validate(data);
                var fill = ParsePaint(GetStyle(root, path, "fill", "currentColor"));
                var stroke = ParsePaint(GetStyle(root, path, "stroke", "none"));
                var width = ParseNumber(GetStyle(root, path, "stroke-width", "1"));
                var cap = ValidateKeyword(GetStyle(root, path, "stroke-linecap", "butt"), "butt", "round", "square");
                var join = ValidateKeyword(GetStyle(root, path, "stroke-linejoin", "miter"), "miter", "round", "bevel");
                var rule = ValidateKeyword(GetStyle(root, path, "fill-rule", "nonzero"), "nonzero", "evenodd");
                paths.Add(
                    $"new SvgPathDefinition({Literal(data!)}, {Boolean(fill)}, {Boolean(stroke)}, {Number(width)}, {Literal(cap)}, {Literal(join)}, {Literal(rule)})");
            }

            if (paths.Count == 0) throw new InvalidDataException("At least one path is required.");
            return new(
                $"new IconDefinition({string.Join(", ", numbers.Select(Number))}, new SvgPathDefinition[] {{ {string.Join(", ", paths)} }})",
                aliases);
        }

        private static string GetStyle(XElement root, XElement path, string name, string fallback)
        {
            return (string?)path.Attribute(name) ?? (string?)root.Attribute(name) ?? fallback;
        }

        private static void ValidateAttributes(XElement element, bool root)
        {
            foreach (var attribute in element.Attributes())
            {
                if (root && attribute.IsNamespaceDeclaration && attribute.Name.LocalName == "xmlns" &&
                    attribute.Value == "http://www.w3.org/2000/svg") continue;
                if (attribute.Name.NamespaceName.Length != 0)
                    throw new InvalidDataException($"Unsupported attribute '{attribute.Name}'.");
                switch (attribute.Name.LocalName)
                {
                    case "fill" or "stroke":
                        ParsePaint(attribute.Value);
                        break;
                    case "stroke-width":
                        if (ParseNumber(attribute.Value) < 0)
                            throw new InvalidDataException("stroke-width cannot be negative.");
                        break;
                    case "stroke-linecap":
                        ValidateKeyword(attribute.Value, "butt", "round", "square");
                        break;
                    case "stroke-linejoin":
                        ValidateKeyword(attribute.Value, "miter", "round", "bevel");
                        break;
                    case "fill-rule":
                        ValidateKeyword(attribute.Value, "nonzero", "evenodd");
                        break;
                    case "viewBox" or "width" or "height" or "data-aliases" when root:
                    case "d" when !root:
                        break;
                    default:
                        throw new InvalidDataException($"Unsupported attribute '{attribute.Name.LocalName}'.");
                }
            }
        }

        private static bool ParsePaint(string value)
        {
            return value switch
            {
                "currentColor" => true,
                "none" => false,
                _ => throw new InvalidDataException($"Unsupported paint '{value}'; use currentColor or none."),
            };
        }

        private static string ValidateKeyword(string value, params string[] allowed)
        {
            return allowed.FirstOrDefault(candidate => candidate == value)
                   ?? throw new InvalidDataException($"Unsupported style keyword '{value}'.");
        }

        internal static double ParseNumber(string value)
        {
            if (!double.TryParse(value, NumberStyles.Float, CultureInfo.InvariantCulture, out var number) ||
                double.IsNaN(number) || double.IsInfinity(number))
                throw new InvalidDataException($"Invalid SVG number '{value}'.");
            return number;
        }

        private static string Literal(string value)
        {
            return SymbolDisplay.FormatLiteral(value, true);
        }

        private static string Number(double value)
        {
            return value.ToString("R", CultureInfo.InvariantCulture) + "d";
        }

        private static string Boolean(bool value)
        {
            return value ? "true" : "false";
        }
    }
}
