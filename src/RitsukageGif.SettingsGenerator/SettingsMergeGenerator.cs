using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace RitsukageGif.SettingsGenerator
{
    [Generator]
    public sealed partial class SettingsMergeGenerator : IIncrementalGenerator
    {
        private const string AttributeName = "RitsukageGif.SettingsGeneration.GenerateSettingsMergeAttribute";

        private static readonly DiagnosticDescriptor UnsupportedModel = new(
            "RGSG001", "Unsupported settings merge model", "{0}", "SettingsGeneration", DiagnosticSeverity.Error, true);

        private static readonly DiagnosticDescriptor UnsupportedProperty = new(
            "RGSG002", "Unsupported settings property",
            "Property '{0}' has unsupported type '{1}'; use an explicit merge strategy instead",
            "SettingsGeneration", DiagnosticSeverity.Error, true);

        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            context.RegisterPostInitializationOutput(static output => output.AddSource(
                "GenerateSettingsMergeAttribute.g.cs", SourceText.From("""
                                                                       // <auto-generated/>
                                                                       #nullable enable
                                                                       namespace RitsukageGif.SettingsGeneration
                                                                       {
                                                                           [global::System.AttributeUsage(global::System.AttributeTargets.Class, AllowMultiple = false, Inherited = false)]
                                                                           [global::System.Diagnostics.Conditional("RG_SETTINGS_GENERATION")]
                                                                           internal sealed class GenerateSettingsMergeAttribute(global::System.Type owner) : global::System.Attribute
                                                                           {
                                                                               public global::System.Type Owner { get; } = owner;
                                                                           }
                                                                       }
                                                                       """, Encoding.UTF8)));

            var models = context.SyntaxProvider.ForAttributeWithMetadataName(AttributeName,
                static (node, _) => node is TypeDeclarationSyntax,
                static (attribute, _) => attribute);
            context.RegisterSourceOutput(models, static (output, model) => Generate(output, model));
        }

        private static void Generate(SourceProductionContext output, GeneratorAttributeSyntaxContext model)
        {
            var record = (INamedTypeSymbol)model.TargetSymbol;
            var owner = model.Attributes[0].ConstructorArguments.FirstOrDefault().Value as INamedTypeSymbol;
            if (!ValidateModel(output, record, owner)) return;
            var properties = record.GetMembers().OfType<IPropertySymbol>()
                .Where(static property => property is
                                          {
                                              IsStatic: false, IsIndexer: false,
                                              GetMethod.DeclaredAccessibility: Accessibility.Public,
                                              SetMethod.DeclaredAccessibility: Accessibility.Public,
                                          } &&
                                          !IsIgnored(property))
                .OrderBy(static property => property.Locations.FirstOrDefault()?.SourceTree?.FilePath,
                    StringComparer.Ordinal)
                .ThenBy(static property => property.Locations.FirstOrDefault()?.SourceSpan.Start).ToArray();
            var supported = true;
            foreach (var property in properties)
            {
                if (IsSupported(property.Type)) continue;
                output.ReportDiagnostic(Diagnostic.Create(UnsupportedProperty, property.Locations.FirstOrDefault(),
                    property.Name, property.Type.ToDisplayString()));
                supported = false;
            }

            if (!supported || owner is null) return;
            var source = Emit(owner, record, properties);
            output.AddSource($"{owner.ToDisplayString()}.{record.Name}.SettingsMerge.g.cs",
                SourceText.From(source, Encoding.UTF8));
        }
    }
}
