using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace RitsukageGif.SettingsGenerator
{
    public sealed partial class SettingsMergeGenerator
    {
        private static string Emit(INamedTypeSymbol owner, INamedTypeSymbol record, IPropertySymbol[] properties)
        {
            var source = new StringBuilder("// <auto-generated/>\n#nullable enable\n");
            var hasNamespace = !owner.ContainingNamespace.IsGlobalNamespace;
            if (hasNamespace)
                source.Append("namespace ").Append(owner.ContainingNamespace.ToDisplayString()).Append("\n{\n");
            var indent = hasNamespace ? "    " : "";
            var member = indent + "    ";
            var body = member + "    ";
            var type = record.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            source.Append(indent).Append(owner.IsRecord ? "partial record " : "partial class ")
                .Append(Escape(owner.Name))
                .Append('\n').Append(indent).Append("{\n");
            source.Append(member).Append("private static bool Same(").Append(type).Append("? left, ")
                .Append(type).Append("? right)\n").Append(member).Append("{\n")
                .Append(body).Append("if (ReferenceEquals(left, right)) return true;\n")
                .Append(body).Append("if (left is null || right is null) return false;\n")
                .Append(body).Append("return ");
            for (var index = 0; index < properties.Length; index++)
            {
                if (index > 0) source.Append(" &&\n").Append(body).Append("       ");
                source.Append(Comparison(properties[index], "left", "right"));
            }

            if (properties.Length == 0) source.Append("true");
            source.Append(";\n").Append(member).Append("}\n\n").Append(member)
                .Append("private static ").Append(type).Append(" Merge(").Append(type).Append(" current, ")
                .Append(type).Append(" baseline, ").Append(type).Append(" edited)\n")
                .Append(member).Append("{\n").Append(body).Append("if (Same(baseline, edited)) return current;\n")
                .Append(body).Append("return current with\n").Append(body).Append("{\n");
            foreach (var property in properties)
            {
                var name = Escape(property.Name);
                source.Append(body).Append("    ").Append(name).Append(" = ")
                    .Append(Comparison(property, "baseline", "edited")).Append("\n")
                    .Append(body).Append("        ? current.").Append(name).Append("\n")
                    .Append(body).Append("        : edited.").Append(name).Append(",\n");
            }

            source.Append(body).Append("};\n").Append(member).Append("}\n").Append(indent).Append("}\n");
            if (hasNamespace) source.Append("}\n");
            return source.ToString();
        }

        private static string Comparison(IPropertySymbol property, string left, string right)
        {
            var type = property.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            var name = Escape(property.Name);
            return
                $"global::System.Collections.Generic.EqualityComparer<{type}>.Default.Equals({left}.{name}, {right}.{name})";
        }

        private static string Escape(string identifier)
        {
            return SyntaxFacts.GetKeywordKind(identifier) == SyntaxKind.None ? identifier : "@" + identifier;
        }
    }
}
